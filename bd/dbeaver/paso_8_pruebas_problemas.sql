BEGIN
    BEGIN
        EXECUTE IMMEDIATE 'CREATE OR REPLACE PROCEDURE SGS_PRUEBA_INVALIDA AS BEGIN SGS_NO_EXISTE; END;';
    EXCEPTION
        WHEN OTHERS THEN
            IF SQLCODE <> -24344 THEN
                RAISE;
            END IF;
    END;
    EXECUTE IMMEDIATE 'CREATE INDEX IDX_PRUEBA_MONITOREO ON SGS_SUCURSAL (SUC_TELEFONO) TABLESPACE SGS_IDX';
    EXECUTE IMMEDIATE 'ALTER INDEX IDX_PRUEBA_MONITOREO UNUSABLE';
    SGS_PKG_PARAMETROS.actualizar('PCT_MAX_TABLESPACE', '0.0001');
    DBMS_SCHEDULER.RUN_JOB('SGS_JOB_REVISION_TABLESPACES', use_current_session => TRUE);
    DBMS_SCHEDULER.RUN_JOB('SGS_JOB_REVISION_OBJETOS', use_current_session => TRUE);
    DBMS_SCHEDULER.RUN_JOB('SGS_JOB_REVISION_INDICES', use_current_session => TRUE);
    SGS_PKG_PARAMETROS.actualizar('PCT_MAX_TABLESPACE', '0.85');
    EXECUTE IMMEDIATE 'DROP INDEX IDX_PRUEBA_MONITOREO';
    EXECUTE IMMEDIATE 'DROP PROCEDURE SGS_PRUEBA_INVALIDA';
EXCEPTION
    WHEN OTHERS THEN
        SGS_PKG_PARAMETROS.actualizar('PCT_MAX_TABLESPACE', '0.85');
        BEGIN EXECUTE IMMEDIATE 'DROP INDEX IDX_PRUEBA_MONITOREO'; EXCEPTION WHEN OTHERS THEN NULL; END;
        BEGIN EXECUTE IMMEDIATE 'DROP PROCEDURE SGS_PRUEBA_INVALIDA'; EXCEPTION WHEN OTHERS THEN NULL; END;
        RAISE;
END;
