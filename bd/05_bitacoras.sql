-- 4. Vistas para consultar la bitacora (encabezado con su detalle)
CREATE OR REPLACE VIEW SGS_VW_BITACORA AS
SELECT b.BIT_ID, b.BIT_FECHA, b.BIT_AREA, b.BIT_TABLA, b.BIT_OPERACION, b.BIT_REGISTRO_ID, b.BIT_ES_CRITICA,
       b.BIT_USUARIO_BD, b.BIT_USUARIO_SO, b.BIT_EQUIPO,
       d.BID_COLUMNA, d.BID_VALOR_ANTERIOR, d.BID_VALOR_NUEVO
  FROM SGS_BITACORA b
  LEFT JOIN SGS_BITACORA_DETALLE d ON d.BID_ID_BITACORA = b.BIT_ID;

-- Solo las operaciones criticas, para la gerencia
CREATE OR REPLACE VIEW SGS_VW_BITACORA_CRITICA AS
SELECT *
  FROM SGS_VW_BITACORA
 WHERE BIT_ES_CRITICA = 'S';
