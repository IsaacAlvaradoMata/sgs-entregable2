-- 05_bitacoras.sql: auditoria de cambios en facturacion, precios, inventario, clientes, proveedores, promociones y descuentos.
-- Se ejecuta como SGS_ADMIN en la PDB del ambiente (desarrollo: FREEPDB1, oficial: SGSPDB en SGSPRI).
-- Requiere haber ejecutado 04_reglas_negocio.sql. Las tablas de bitacora estan en SGS_AUD desde 02_modelo.sql.

-- 1. Validar que la sesion es del dueno del esquema
DECLARE
    v_usuario VARCHAR2(128) := SYS_CONTEXT('USERENV', 'SESSION_USER');
BEGIN
    IF v_usuario <> 'SGS_ADMIN' THEN
        RAISE_APPLICATION_ERROR(-20001, 'Ejecutar conectado como SGS_ADMIN, no como ' || v_usuario);
    END IF;
END;
/

-- 2. Registro de la bitacora
-- Cada trigger de auditoria llama a columna() por cada columna de la tabla y al final a guardar().
-- Solo quedan las columnas cuyo valor cambio; una actualizacion que no cambia nada no deja rastro.
-- La operacion es critica si es un borrado, si cambia una columna marcada como critica o si el trigger la marca.
-- El registro va en la misma transaccion: si la operacion se deshace, su rastro tambien.
CREATE OR REPLACE PACKAGE SGS_PKG_BITACORA AS
    PROCEDURE iniciar;
    PROCEDURE columna (p_columna IN VARCHAR2, p_anterior IN VARCHAR2, p_nuevo IN VARCHAR2, p_es_critica IN VARCHAR2 DEFAULT 'N');
    PROCEDURE columna (p_columna IN VARCHAR2, p_anterior IN NUMBER,   p_nuevo IN NUMBER,   p_es_critica IN VARCHAR2 DEFAULT 'N');
    PROCEDURE columna (p_columna IN VARCHAR2, p_anterior IN DATE,     p_nuevo IN DATE,     p_es_critica IN VARCHAR2 DEFAULT 'N');
    -- Indica si el cambio lo hace el programa indicado (un package o trigger que esta en la pila de llamadas)
    FUNCTION desde (p_programa IN VARCHAR2) RETURN BOOLEAN;
    PROCEDURE guardar (p_area        IN VARCHAR2,
                       p_tabla       IN VARCHAR2,
                       p_operacion   IN VARCHAR2,
                       p_registro_id IN NUMBER,
                       p_es_critica  IN VARCHAR2 DEFAULT 'N');
END;
/

CREATE OR REPLACE PACKAGE BODY SGS_PKG_BITACORA AS

    TYPE t_columna IS RECORD (columna VARCHAR2(128), anterior VARCHAR2(250), nuevo VARCHAR2(250));
    TYPE t_columnas IS TABLE OF t_columna INDEX BY PLS_INTEGER;

    g_columnas t_columnas;
    g_critica  BOOLEAN := FALSE;

    PROCEDURE iniciar IS
    BEGIN
        g_columnas.DELETE;
        g_critica := FALSE;
    END;

    -- Un nulo contra un valor tambien es un cambio; dos nulos no
    PROCEDURE agregar (p_columna IN VARCHAR2, p_anterior IN VARCHAR2, p_nuevo IN VARCHAR2, p_es_critica IN VARCHAR2) IS
        v_i PLS_INTEGER;
    BEGIN
        IF p_anterior = p_nuevo OR (p_anterior IS NULL AND p_nuevo IS NULL) THEN
            RETURN;
        END IF;
        v_i := g_columnas.COUNT + 1;
        g_columnas(v_i).columna  := p_columna;
        g_columnas(v_i).anterior := SUBSTR(p_anterior, 1, 250);
        g_columnas(v_i).nuevo    := SUBSTR(p_nuevo, 1, 250);
        IF p_es_critica = 'S' THEN
            g_critica := TRUE;
        END IF;
    END;

    PROCEDURE columna (p_columna IN VARCHAR2, p_anterior IN VARCHAR2, p_nuevo IN VARCHAR2, p_es_critica IN VARCHAR2 DEFAULT 'N') IS
    BEGIN
        agregar(p_columna, p_anterior, p_nuevo, p_es_critica);
    END;

    PROCEDURE columna (p_columna IN VARCHAR2, p_anterior IN NUMBER, p_nuevo IN NUMBER, p_es_critica IN VARCHAR2 DEFAULT 'N') IS
    BEGIN
        agregar(p_columna,
                TO_CHAR(p_anterior, 'TM9', 'NLS_NUMERIC_CHARACTERS=''.,'''),
                TO_CHAR(p_nuevo, 'TM9', 'NLS_NUMERIC_CHARACTERS=''.,'''),
                p_es_critica);
    END;

    PROCEDURE columna (p_columna IN VARCHAR2, p_anterior IN DATE, p_nuevo IN DATE, p_es_critica IN VARCHAR2 DEFAULT 'N') IS
    BEGIN
        agregar(p_columna,
                TO_CHAR(p_anterior, 'YYYY-MM-DD HH24:MI:SS'),
                TO_CHAR(p_nuevo, 'YYYY-MM-DD HH24:MI:SS'),
                p_es_critica);
    END;

    FUNCTION desde (p_programa IN VARCHAR2) RETURN BOOLEAN IS
    BEGIN
        RETURN INSTR(UPPER(DBMS_UTILITY.FORMAT_CALL_STACK), UPPER(p_programa)) > 0;
    END;

    PROCEDURE guardar (p_area        IN VARCHAR2,
                       p_tabla       IN VARCHAR2,
                       p_operacion   IN VARCHAR2,
                       p_registro_id IN NUMBER,
                       p_es_critica  IN VARCHAR2 DEFAULT 'N') IS
        v_id      SGS_BITACORA.BIT_ID%TYPE;
        v_critica SGS_BITACORA.BIT_ES_CRITICA%TYPE := 'N';
    BEGIN
        IF p_operacion = 'U' AND g_columnas.COUNT = 0 THEN
            iniciar;
            RETURN;
        END IF;

        IF p_es_critica = 'S' OR p_operacion = 'D' OR (p_operacion = 'U' AND g_critica) THEN
            v_critica := 'S';
        END IF;

        INSERT INTO SGS_BITACORA (BIT_ID, BIT_AREA, BIT_TABLA, BIT_OPERACION, BIT_REGISTRO_ID, BIT_ES_CRITICA)
        VALUES (SEQ_BITACORA.NEXTVAL, p_area, p_tabla, p_operacion, p_registro_id, v_critica)
        RETURNING BIT_ID INTO v_id;

        FOR v_i IN 1 .. g_columnas.COUNT LOOP
            INSERT INTO SGS_BITACORA_DETALLE (BID_ID, BID_ID_BITACORA, BID_COLUMNA, BID_VALOR_ANTERIOR, BID_VALOR_NUEVO)
            VALUES (SEQ_BITACORA_DETALLE.NEXTVAL, v_id, g_columnas(v_i).columna, g_columnas(v_i).anterior, g_columnas(v_i).nuevo);
        END LOOP;

        iniciar;
    EXCEPTION
        WHEN OTHERS THEN
            iniciar;
            RAISE;
    END;

END;
/

-- 3. Triggers de auditoria, uno por tabla
-- Insercion: valores nuevos; actualizacion: solo lo que cambio; borrado: valores anteriores. Todo borrado es critico.
-- Si la auditoria falla, el error queda en SGS_BITACORA_ERROR y la operacion sigue (no se bloquea el negocio).
-- El cuarto parametro de columna() marca si cambiar esa columna en un registro existente es critico.

-- Facturacion: anular o modificar una factura existente o sus lineas, todo pago y toda nota de credito

CREATE OR REPLACE TRIGGER TRG_AUD_FV
AFTER INSERT OR UPDATE OR DELETE ON SGS_FACTURA_VENTA
FOR EACH ROW
BEGIN
    SGS_PKG_BITACORA.iniciar;
    SGS_PKG_BITACORA.columna('FV_ID_CLIENTE', :OLD.FV_ID_CLIENTE, :NEW.FV_ID_CLIENTE, 'S');
    SGS_PKG_BITACORA.columna('FV_ID_SUCURSAL', :OLD.FV_ID_SUCURSAL, :NEW.FV_ID_SUCURSAL, 'S');
    SGS_PKG_BITACORA.columna('FV_ID_USUARIO', :OLD.FV_ID_USUARIO, :NEW.FV_ID_USUARIO, 'S');
    SGS_PKG_BITACORA.columna('FV_FECHA', :OLD.FV_FECHA, :NEW.FV_FECHA, 'S');
    SGS_PKG_BITACORA.columna('FV_SUBTOTAL', :OLD.FV_SUBTOTAL, :NEW.FV_SUBTOTAL, 'S');
    SGS_PKG_BITACORA.columna('FV_DESCUENTO', :OLD.FV_DESCUENTO, :NEW.FV_DESCUENTO, 'S');
    SGS_PKG_BITACORA.columna('FV_IMPUESTO', :OLD.FV_IMPUESTO, :NEW.FV_IMPUESTO, 'S');
    SGS_PKG_BITACORA.columna('FV_TOTAL', :OLD.FV_TOTAL, :NEW.FV_TOTAL, 'S');
    SGS_PKG_BITACORA.columna('FV_ES_CREDITO', :OLD.FV_ES_CREDITO, :NEW.FV_ES_CREDITO, 'S');
    SGS_PKG_BITACORA.columna('FV_ESTADO', :OLD.FV_ESTADO, :NEW.FV_ESTADO, CASE WHEN :NEW.FV_ESTADO = 'N' THEN 'S' ELSE 'N' END);
    SGS_PKG_BITACORA.guardar('FACTURACION', 'SGS_FACTURA_VENTA', CASE WHEN INSERTING THEN 'I' WHEN UPDATING THEN 'U' ELSE 'D' END,
                             NVL(:NEW.FV_ID, :OLD.FV_ID));
EXCEPTION
    WHEN OTHERS THEN
        SGS_PKG_ERRORES.registrar('TRG_AUD_FV');
END;
/

