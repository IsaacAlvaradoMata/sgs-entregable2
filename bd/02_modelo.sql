    CONSTRAINT CK_CLI_ES_PREFERENCIAL CHECK (CLI_ES_PREFERENCIAL IN ('S', 'N')),
    CONSTRAINT CK_CLI_ES_DEFECTO CHECK (CLI_ES_DEFECTO IN ('S', 'N')),
