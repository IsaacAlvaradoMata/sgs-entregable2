COMMENT ON COLUMN SGS_CLIENTE.CLI_NOMBRE IS 'Nombre de la persona o razon social de la empresa';
COMMENT ON COLUMN SGS_CLIENTE.CLI_TIPO_PERSONA IS 'NACIONAL, EXTRANJERO o EMPRESA';
COMMENT ON COLUMN SGS_CLIENTE.CLI_DIRECCION_CASA IS 'Direccion de la casa';
COMMENT ON COLUMN SGS_CLIENTE.CLI_DIRECCION_TRABAJO IS 'Direccion del trabajo';
COMMENT ON COLUMN SGS_CLIENTE.CLI_TELEFONO IS 'Telefono';
COMMENT ON COLUMN SGS_CLIENTE.CLI_ID_PAIS_NACIONALIDAD IS 'Pais de nacionalidad';
