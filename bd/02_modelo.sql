CREATE TABLE SGS_PADRON (
    PAD_ID               NUMBER,
    PAD_CEDULA           VARCHAR2(9)  NOT NULL,
    PAD_NOMBRE           VARCHAR2(50) NOT NULL,
    PAD_APELLIDO1        VARCHAR2(50),
