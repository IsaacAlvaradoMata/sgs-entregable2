COMMENT ON COLUMN SGS_CLIENTE.CLI_FAX IS 'Fax';
COMMENT ON COLUMN SGS_CLIENTE.CLI_EMAIL IS 'Correo electronico; recibe el aviso del 85 % del credito';
COMMENT ON COLUMN SGS_CLIENTE.CLI_FECHA_INGRESO IS 'Fecha de ingreso como cliente';
COMMENT ON COLUMN SGS_CLIENTE.CLI_ESTADO IS 'A = activo, I = inactivo';
COMMENT ON COLUMN SGS_CLIENTE.CLI_ES_PREFERENCIAL IS 'S = puede comprar a credito, N = solo contado';
