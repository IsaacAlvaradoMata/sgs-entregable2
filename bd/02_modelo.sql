-- Proveedores de los descuentos de criterio PROVEEDOR
INSERT INTO SGS_DESCUENTO_PROVEEDOR (DSP_ID, DSP_ID_DESCUENTO, DSP_ID_PROVEEDOR)
SELECT SEQ_DESCUENTO_PROVEEDOR.NEXTVAL, ds.DSC_ID, pr.PRV_ID
  FROM (SELECT 'Semana de Bebidas Tropicales' AS DESCUENTO, '3101100002' AS PROVEEDOR FROM DUAL
        UNION ALL SELECT 'Proveedores aliados', '3101100001' FROM DUAL
        UNION ALL SELECT 'Proveedores aliados', '3101100003' FROM DUAL
        UNION ALL SELECT 'Proveedores aliados', '3101100004' FROM DUAL
        UNION ALL SELECT 'Proveedores aliados', '3101100005' FROM DUAL) d
  JOIN SGS_DESCUENTO ds ON ds.DSC_NOMBRE = d.DESCUENTO
  JOIN SGS_PROVEEDOR pr ON pr.PRV_CEDULA_JURIDICA = d.PROVEEDOR;

