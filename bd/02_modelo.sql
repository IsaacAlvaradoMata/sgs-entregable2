-- 1. Validar que la sesion es del dueno del esquema
DECLARE
    v_usuario VARCHAR2(128) := SYS_CONTEXT('USERENV', 'SESSION_USER');
BEGIN
    IF v_usuario <> 'SGS_ADMIN' THEN
        RAISE_APPLICATION_ERROR(-20001, 'Ejecutar conectado como SGS_ADMIN, no como ' || v_usuario);
    END IF;
END;
/

-- 2. Catalogos base

-- Paises: nacionalidad y pais de residencia de los clientes
CREATE SEQUENCE SEQ_PAIS INCREMENT BY 1 MINVALUE 1 NOCYCLE NOCACHE NOORDER;

CREATE TABLE SGS_PAIS (
    PAI_ID      NUMBER,
    PAI_CODIGO  VARCHAR2(3)   NOT NULL,
    PAI_NOMBRE  VARCHAR2(100) NOT NULL,
    CONSTRAINT PK_PAIS PRIMARY KEY (PAI_ID) USING INDEX TABLESPACE SGS_IDX,
    CONSTRAINT UK_PAI_CODIGO UNIQUE (PAI_CODIGO) USING INDEX TABLESPACE SGS_IDX,
    CONSTRAINT UK_PAI_NOMBRE UNIQUE (PAI_NOMBRE) USING INDEX TABLESPACE SGS_IDX,
    CONSTRAINT CK_PAI_CODIGO CHECK (REGEXP_LIKE(PAI_CODIGO, '^[A-Z]{3}$'))
) TABLESPACE SGS_DATA;

COMMENT ON TABLE SGS_PAIS IS 'Catalogo de paises para la nacionalidad y el pais de residencia de los clientes';
COMMENT ON COLUMN SGS_PAIS.PAI_ID IS 'Identificador del pais (SEQ_PAIS)';
COMMENT ON COLUMN SGS_PAIS.PAI_CODIGO IS 'Codigo ISO 3166-1 alfa-3 (ej. CRI)';
COMMENT ON COLUMN SGS_PAIS.PAI_NOMBRE IS 'Nombre del pais';

-- Sucursales: la bodega central es la sucursal con SUC_ES_CENTRAL = 'S'
CREATE SEQUENCE SEQ_SUCURSAL INCREMENT BY 1 MINVALUE 1 NOCYCLE NOCACHE NOORDER;

CREATE TABLE SGS_SUCURSAL (
    SUC_ID          NUMBER,
    SUC_NOMBRE      VARCHAR2(100) NOT NULL,
    SUC_DIRECCION   VARCHAR2(200),
    SUC_TELEFONO    VARCHAR2(50),
    SUC_ES_CENTRAL  VARCHAR2(1) DEFAULT 'N' NOT NULL,
    CONSTRAINT PK_SUCURSAL PRIMARY KEY (SUC_ID) USING INDEX TABLESPACE SGS_IDX,
    CONSTRAINT UK_SUC_NOMBRE UNIQUE (SUC_NOMBRE) USING INDEX TABLESPACE SGS_IDX,
    CONSTRAINT CK_SUC_ES_CENTRAL CHECK (SUC_ES_CENTRAL IN ('S', 'N'))
) TABLESPACE SGS_DATA;

-- Solo una bodega central: las filas 'N' dan NULL y no chocan en el indice unico
CREATE UNIQUE INDEX UX_SUC_UNICA_CENTRAL
    ON SGS_SUCURSAL (CASE WHEN SUC_ES_CENTRAL = 'S' THEN 1 END) TABLESPACE SGS_IDX;

COMMENT ON TABLE SGS_SUCURSAL IS 'Sucursales de la cadena; la bodega central es la sucursal marcada como central';
COMMENT ON COLUMN SGS_SUCURSAL.SUC_ID IS 'Identificador de la sucursal (SEQ_SUCURSAL)';
COMMENT ON COLUMN SGS_SUCURSAL.SUC_NOMBRE IS 'Nombre de la sucursal';
COMMENT ON COLUMN SGS_SUCURSAL.SUC_DIRECCION IS 'Direccion de la sucursal';
COMMENT ON COLUMN SGS_SUCURSAL.SUC_TELEFONO IS 'Telefono de la sucursal';
COMMENT ON COLUMN SGS_SUCURSAL.SUC_ES_CENTRAL IS 'S = bodega central, N = sucursal';

-- Tipos de negocio: la instancia trabaja con un solo tipo activo (supermercado, ferreteria, etc.)
CREATE SEQUENCE SEQ_TIPO_NEGOCIO INCREMENT BY 1 MINVALUE 1 NOCYCLE NOCACHE NOORDER;

CREATE TABLE SGS_TIPO_NEGOCIO (
    TNE_ID           NUMBER,
    TNE_NOMBRE       VARCHAR2(100) NOT NULL,
    TNE_DESCRIPCION  VARCHAR2(200),
    TNE_ES_ACTIVO    VARCHAR2(1) DEFAULT 'N' NOT NULL,
    CONSTRAINT PK_TIPO_NEGOCIO PRIMARY KEY (TNE_ID) USING INDEX TABLESPACE SGS_IDX,
    CONSTRAINT UK_TNE_NOMBRE UNIQUE (TNE_NOMBRE) USING INDEX TABLESPACE SGS_IDX,
    CONSTRAINT CK_TNE_ES_ACTIVO CHECK (TNE_ES_ACTIVO IN ('S', 'N'))
) TABLESPACE SGS_DATA;

-- Solo un tipo de negocio activo, mismo mecanismo que la bodega central
CREATE UNIQUE INDEX UX_TNE_UNICO_ACTIVO
