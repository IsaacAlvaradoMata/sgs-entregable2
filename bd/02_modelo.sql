COMMENT ON TABLE SGS_TIPO_NEGOCIO IS 'Tipos de negocio configurables; los negocios son mutuamente excluyentes';
COMMENT ON COLUMN SGS_TIPO_NEGOCIO.TNE_ID IS 'Identificador del tipo de negocio (SEQ_TIPO_NEGOCIO)';
COMMENT ON COLUMN SGS_TIPO_NEGOCIO.TNE_NOMBRE IS 'Nombre del tipo de negocio';
COMMENT ON COLUMN SGS_TIPO_NEGOCIO.TNE_DESCRIPCION IS 'Descripcion del tipo de negocio';
COMMENT ON COLUMN SGS_TIPO_NEGOCIO.TNE_ES_ACTIVO IS 'S = tipo de negocio de la instancia, N = no activo';

-- Usuarios del sistema (cajeros, gerentes); no son usuarios de Oracle
CREATE SEQUENCE SEQ_USUARIO INCREMENT BY 1 MINVALUE 1 NOCYCLE NOCACHE NOORDER;

CREATE TABLE SGS_USUARIO (
    USU_ID             NUMBER,
    USU_NOMBRE         VARCHAR2(100) NOT NULL,
    USU_USERNAME       VARCHAR2(50)  NOT NULL,
    USU_PASSWORD_HASH  VARCHAR2(64)  NOT NULL,
    USU_SAL            VARCHAR2(32)  NOT NULL,
    USU_ESTADO         VARCHAR2(1) DEFAULT 'A' NOT NULL,
    USU_ID_SUCURSAL    NUMBER,
    CONSTRAINT PK_USUARIO PRIMARY KEY (USU_ID) USING INDEX TABLESPACE SGS_IDX,
    CONSTRAINT UK_USU_USERNAME UNIQUE (USU_USERNAME) USING INDEX TABLESPACE SGS_IDX,
    CONSTRAINT CK_USU_ESTADO CHECK (USU_ESTADO IN ('A', 'I')),
    CONSTRAINT FK_USU_SUCURSAL FOREIGN KEY (USU_ID_SUCURSAL)
        REFERENCES SGS_SUCURSAL (SUC_ID)
) TABLESPACE SGS_DATA;

CREATE INDEX IDX_USU_SUCURSAL ON SGS_USUARIO (USU_ID_SUCURSAL) TABLESPACE SGS_IDX;

COMMENT ON TABLE SGS_USUARIO IS 'Usuarios del sistema (cajeros, gerentes); identifican al cajero de facturas y cierres';
COMMENT ON COLUMN SGS_USUARIO.USU_ID IS 'Identificador del usuario (SEQ_USUARIO)';
COMMENT ON COLUMN SGS_USUARIO.USU_NOMBRE IS 'Nombre completo del usuario';
COMMENT ON COLUMN SGS_USUARIO.USU_USERNAME IS 'Nombre de usuario para inicio de sesion en el sistema';
COMMENT ON COLUMN SGS_USUARIO.USU_PASSWORD_HASH IS 'Hash SHA-256 (DBMS_CRYPTO) de la sal + contrasena, en hexadecimal';
COMMENT ON COLUMN SGS_USUARIO.USU_SAL IS 'Sal aleatoria del usuario, en hexadecimal';
COMMENT ON COLUMN SGS_USUARIO.USU_ESTADO IS 'A = activo, I = inactivo';
COMMENT ON COLUMN SGS_USUARIO.USU_ID_SUCURSAL IS 'Sucursal asignada; nula para usuarios sin sucursal (ej. gerencia)';

