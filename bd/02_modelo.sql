-- Articulos facturables: supertipo de productos y servicios
CREATE SEQUENCE SEQ_ARTICULO_FACTURABLE INCREMENT BY 1 MINVALUE 1 NOCYCLE NOCACHE NOORDER;

CREATE TABLE SGS_ARTICULO_FACTURABLE (
    ART_ID               NUMBER,
    ART_NOMBRE           VARCHAR2(100) NOT NULL,
    ART_EXENTO_IMPUESTO  VARCHAR2(1) DEFAULT 'N' NOT NULL,
    ART_PCT_IMPUESTO     NUMBER(5,4) DEFAULT 0 NOT NULL,
    ART_ESTADO           VARCHAR2(1) DEFAULT 'A' NOT NULL,
    CONSTRAINT PK_ARTICULO_FACTURABLE PRIMARY KEY (ART_ID) USING INDEX TABLESPACE SGS_IDX,
    CONSTRAINT CK_ART_EXENTO_IMPUESTO CHECK (ART_EXENTO_IMPUESTO IN ('S', 'N')),
    CONSTRAINT CK_ART_PCT_IMPUESTO CHECK (ART_PCT_IMPUESTO BETWEEN 0 AND 1),
