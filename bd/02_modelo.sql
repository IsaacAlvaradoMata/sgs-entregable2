-- Clientes: datos comunes de personas y empresas; el limite de credito vive en su cuenta por cobrar
CREATE SEQUENCE SEQ_CLIENTE INCREMENT BY 1 MINVALUE 1 NOCYCLE NOCACHE NOORDER;

CREATE TABLE SGS_CLIENTE (
    CLI_ID                    NUMBER,
    CLI_CEDULA                VARCHAR2(30)  NOT NULL,
    CLI_NOMBRE                VARCHAR2(100) NOT NULL,
    CLI_TIPO_PERSONA          VARCHAR2(10)  NOT NULL,
    CLI_DIRECCION_CASA        VARCHAR2(200),
    CLI_DIRECCION_TRABAJO     VARCHAR2(200),
    CLI_TELEFONO              VARCHAR2(50),
    CLI_ID_PAIS_NACIONALIDAD  NUMBER,
    CLI_ID_PAIS_RESIDENCIA    NUMBER,
    CLI_FAX                   VARCHAR2(50),
    CLI_EMAIL                 VARCHAR2(100),
    CLI_FECHA_INGRESO         DATE DEFAULT SYSDATE NOT NULL,
    CLI_ESTADO                VARCHAR2(1) DEFAULT 'A' NOT NULL,
    CLI_ES_PREFERENCIAL       VARCHAR2(1) DEFAULT 'N' NOT NULL,
    CLI_ES_DEFECTO            VARCHAR2(1) DEFAULT 'N' NOT NULL,
    CONSTRAINT PK_CLIENTE PRIMARY KEY (CLI_ID) USING INDEX TABLESPACE SGS_IDX,
    CONSTRAINT UK_CLI_CEDULA UNIQUE (CLI_CEDULA) USING INDEX TABLESPACE SGS_IDX,
    CONSTRAINT CK_CLI_TIPO_PERSONA CHECK (CLI_TIPO_PERSONA IN ('NACIONAL', 'EXTRANJERO', 'EMPRESA')),
    -- La cedula nacional sigue el formato del padron; la de extranjeros varia en tipo y tamano
    CONSTRAINT CK_CLI_CEDULA_NACIONAL CHECK (CLI_TIPO_PERSONA <> 'NACIONAL' OR REGEXP_LIKE(CLI_CEDULA, '^[0-9]{9}$')),
    CONSTRAINT CK_CLI_ESTADO CHECK (CLI_ESTADO IN ('A', 'I')),
    CONSTRAINT CK_CLI_ES_PREFERENCIAL CHECK (CLI_ES_PREFERENCIAL IN ('S', 'N')),
    CONSTRAINT CK_CLI_ES_DEFECTO CHECK (CLI_ES_DEFECTO IN ('S', 'N')),
    CONSTRAINT FK_CLI_PAIS_NACIONALIDAD FOREIGN KEY (CLI_ID_PAIS_NACIONALIDAD)
        REFERENCES SGS_PAIS (PAI_ID),
    CONSTRAINT FK_CLI_PAIS_RESIDENCIA FOREIGN KEY (CLI_ID_PAIS_RESIDENCIA)
        REFERENCES SGS_PAIS (PAI_ID)
) TABLESPACE SGS_DATA;

-- Solo un cliente por defecto para las facturas sin cliente registrado
CREATE UNIQUE INDEX UX_CLI_UNICO_DEFECTO
    ON SGS_CLIENTE (CASE WHEN CLI_ES_DEFECTO = 'S' THEN 1 END) TABLESPACE SGS_IDX;

CREATE INDEX IDX_CLI_PAIS_NACIONALIDAD ON SGS_CLIENTE (CLI_ID_PAIS_NACIONALIDAD) TABLESPACE SGS_IDX;
CREATE INDEX IDX_CLI_PAIS_RESIDENCIA ON SGS_CLIENTE (CLI_ID_PAIS_RESIDENCIA) TABLESPACE SGS_IDX;

COMMENT ON TABLE SGS_CLIENTE IS 'Clientes personas o empresas; su limite y saldo estan en la cuenta por cobrar';
