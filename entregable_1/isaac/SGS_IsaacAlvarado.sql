/* ----------------------------------------------------------------
   1. TABLESPACES
   Ruta de datafile detectada en tiempo de ejecucion (ver notas de
   ejecucion adjuntas).
   ---------------------------------------------------------------- */
DECLARE
    v_datafile  VARCHAR2(500);
    v_dir       VARCHAR2(500);
BEGIN
    SELECT file_name INTO v_datafile
    FROM dba_data_files
    WHERE tablespace_name = 'SYSTEM'
    AND ROWNUM = 1;

    v_dir := SUBSTR(v_datafile, 1, INSTR(v_datafile, '/', -1));

    EXECUTE IMMEDIATE 'CREATE TABLESPACE SGS_DATA DATAFILE ''' || v_dir ||
        'sgs_data01.dbf'' SIZE 200M AUTOEXTEND ON NEXT 50M MAXSIZE UNLIMITED';

    EXECUTE IMMEDIATE 'CREATE TABLESPACE SGS_IDX DATAFILE ''' || v_dir ||
        'sgs_idx01.dbf'' SIZE 100M AUTOEXTEND ON NEXT 20M MAXSIZE UNLIMITED';

    EXECUTE IMMEDIATE 'CREATE TABLESPACE SGS_AUD DATAFILE ''' || v_dir ||
        'sgs_aud01.dbf'' SIZE 50M AUTOEXTEND ON NEXT 10M MAXSIZE UNLIMITED';
END;
/

/* ----------------------------------------------------------------
   2. USUARIO PROPIETARIO DEL ESQUEMA
   ---------------------------------------------------------------- */
CREATE USER IALVARADO
    IDENTIFIED BY admin
    DEFAULT TABLESPACE SGS_DATA
    TEMPORARY TABLESPACE TEMP
    QUOTA UNLIMITED ON SGS_DATA
    QUOTA UNLIMITED ON SGS_IDX
    QUOTA UNLIMITED ON SGS_AUD;

