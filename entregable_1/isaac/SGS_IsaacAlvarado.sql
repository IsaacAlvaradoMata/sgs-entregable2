/* ==================================================================
   12. VISTA - PRECIO DE VENTA
   Orden: costo -> utilidad -> descuento activo (FAMILIA/PROVEEDOR
   vigente) -> impuesto (13%, si no exento). DFV_DESCUENTO es un
   ajuste aparte de punto de venta, no forma parte de esta formula.
   ================================================================== */

CREATE OR REPLACE VIEW IALVARADO.SGS_VW_PRECIO_VENTA AS
WITH DESCUENTO_ACTIVO AS (
    SELECT
        p.PRO_ID,
        NVL(MAX(d.DSC_PORCENTAJE), 0) AS PCT_DESCUENTO
    FROM IALVARADO.SGS_PRODUCTO p
    LEFT JOIN IALVARADO.SGS_DESCUENTO d
        ON d.DSC_FECHA_INICIO <= SYSDATE
       AND (d.DSC_FECHA_FIN IS NULL OR d.DSC_FECHA_FIN >= SYSDATE)
       AND (
             (d.DSC_TIPO_CRITERIO = 'FAMILIA' AND EXISTS (
                 SELECT 1 FROM IALVARADO.SGS_DESCUENTO_FAMILIA df
                 WHERE df.DSF_ID_DESCUENTO = d.DSC_ID
                   AND df.DSF_ID_FAMILIA = p.PRO_ID_FAMILIA))
          OR (d.DSC_TIPO_CRITERIO = 'PROVEEDOR' AND EXISTS (
                 SELECT 1 FROM IALVARADO.SGS_DESCUENTO_PROVEEDOR dp
                 WHERE dp.DSP_ID_DESCUENTO = d.DSC_ID
                   AND dp.DSP_ID_PROVEEDOR = p.PRO_ID_PROVEEDOR))
           )
    GROUP BY p.PRO_ID
)
SELECT
    p.PRO_ID,
    p.PRO_CODIGO,
    a.ART_NOMBRE,
    ps.PS_ID_SUCURSAL,
    p.PRO_PRECIO_COSTO,
    ps.PS_PCT_UTILIDAD,
    da.PCT_DESCUENTO           AS PCT_DESCUENTO_ACTIVO,
    a.ART_EXENTO_IMPUESTO,
    ROUND(
        p.PRO_PRECIO_COSTO
        * (1 + ps.PS_PCT_UTILIDAD)
        * (1 - da.PCT_DESCUENTO)
        * (CASE WHEN a.ART_EXENTO_IMPUESTO = 'S' THEN 1 ELSE 1.13 END)
    , 2)                        AS PRECIO_VENTA
FROM IALVARADO.SGS_PRODUCTO p
JOIN IALVARADO.SGS_ARTICULO_FACTURABLE a ON a.ART_ID = p.PRO_ID_ARTICULO
JOIN IALVARADO.SGS_PRODUCTO_SUCURSAL ps ON ps.PS_ID_PRODUCTO = p.PRO_ID
JOIN DESCUENTO_ACTIVO da ON da.PRO_ID = p.PRO_ID;

COMMENT ON TABLE IALVARADO.SGS_VW_PRECIO_VENTA IS 'Precio de venta calculado por producto y sucursal (costo, utilidad, descuento activo e impuesto)';


