    DESCUENTO         NUMBER(14,2) DEFAULT 0 NOT NULL,
    IMPUESTO          NUMBER(14,2) DEFAULT 0 NOT NULL,
    TOTAL             NUMBER(14,2) NOT NULL,
    CONDICION_COMPRA  VARCHAR2(10) NOT NULL,
    ESTADO            VARCHAR2(15) DEFAULT 'ACTIVA' NOT NULL,
    CONSTRAINT PK_COMPRA
        PRIMARY KEY (ID_COMPRA)
        USING INDEX TABLESPACE TS_INDICES,
    CONSTRAINT UQ_COMPRA_FACTURA
        UNIQUE (ID_PROVEEDOR, NUMERO_FACTURA)
        USING INDEX TABLESPACE TS_INDICES,
    CONSTRAINT FK_COMPRA_PROVEEDOR
        FOREIGN KEY (ID_PROVEEDOR)
        REFERENCES PROVEEDOR(ID_PROVEEDOR),
    CONSTRAINT FK_COMPRA_BODEGA
        FOREIGN KEY (ID_BODEGA)
        REFERENCES BODEGA(ID_BODEGA),
    CONSTRAINT CK_COMPRA_MONTOS
        CHECK (
            SUBTOTAL >= 0 AND DESCUENTO >= 0
            AND IMPUESTO >= 0 AND TOTAL >= 0
        ),
    CONSTRAINT CK_COMPRA_CONDICION
        CHECK (CONDICION_COMPRA IN ('CONTADO','CREDITO')),
    CONSTRAINT CK_COMPRA_ESTADO
        CHECK (ESTADO IN ('ACTIVA','ANULADA','DEVUELTA'))
) TABLESPACE TS_DATOS;

