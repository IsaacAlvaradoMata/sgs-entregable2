-- 11. Si esta consulta NO devuelve filas, todas las tablas tienen al menos 5 registros.
-- Se usa PL/SQL para revisar dinamicamente todas las tablas.
SET SERVEROUTPUT ON;
DECLARE
    v_count NUMBER;
    v_fallos NUMBER := 0;
BEGIN
    FOR r IN (SELECT TABLE_NAME FROM USER_TABLES ORDER BY TABLE_NAME) LOOP
        EXECUTE IMMEDIATE 'SELECT COUNT(*) FROM ' || DBMS_ASSERT.SIMPLE_SQL_NAME(r.TABLE_NAME)
        INTO v_count;

        IF v_count < 5 THEN
            DBMS_OUTPUT.PUT_LINE('FALLO: ' || r.TABLE_NAME || ' tiene ' || v_count || ' registros');
            v_fallos := v_fallos + 1;
        END IF;
    END LOOP;

    IF v_fallos = 0 THEN
        DBMS_OUTPUT.PUT_LINE('OK: Todas las tablas tienen al menos 5 registros.');
    END IF;
END;
/

