PROMPT ============================================================
PROMPT SECCION A - INFRAESTRUCTURA (EJECUTAR COMO SYSTEM)
PROMPT ============================================================

ALTER SESSION SET CONTAINER = FREEPDB1;

-- ---------------------------------------------------------------------------
-- A.1 TABLESPACES
-- ---------------------------------------------------------------------------

CREATE TABLESPACE TS_DATOS
DATAFILE '/opt/oracle/oradata/FREE/FREEPDB1/ts_datos01.dbf'
SIZE 100M
AUTOEXTEND ON
NEXT 20M
MAXSIZE 1000M;

CREATE TABLESPACE TS_INDICES
DATAFILE '/opt/oracle/oradata/FREE/FREEPDB1/ts_indices01.dbf'
SIZE 50M
AUTOEXTEND ON
NEXT 10M
MAXSIZE 500M;

CREATE TABLESPACE TS_AUDITORIA
DATAFILE '/opt/oracle/oradata/FREE/FREEPDB1/ts_auditoria01.dbf'
SIZE 50M
AUTOEXTEND ON
NEXT 10M
MAXSIZE 500M;

-- ---------------------------------------------------------------------------
-- A.2 USUARIO PROPIETARIO DEL ESQUEMA
-- ---------------------------------------------------------------------------

CREATE USER CADENA_NEGOCIOS
IDENTIFIED BY Cadena2026
DEFAULT TABLESPACE TS_DATOS
TEMPORARY TABLESPACE TEMP;

GRANT CREATE SESSION TO CADENA_NEGOCIOS;
GRANT CREATE TABLE TO CADENA_NEGOCIOS;
GRANT CREATE SEQUENCE TO CADENA_NEGOCIOS;
GRANT CREATE VIEW TO CADENA_NEGOCIOS;
GRANT CREATE TRIGGER TO CADENA_NEGOCIOS;
GRANT CREATE PROCEDURE TO CADENA_NEGOCIOS;

ALTER USER CADENA_NEGOCIOS QUOTA UNLIMITED ON TS_DATOS;
ALTER USER CADENA_NEGOCIOS QUOTA UNLIMITED ON TS_INDICES;
ALTER USER CADENA_NEGOCIOS QUOTA UNLIMITED ON TS_AUDITORIA;

-- VERIFICACION DE INFRAESTRUCTURA
SELECT USER AS USUARIO_ACTUAL,
       SYS_CONTEXT('USERENV','CON_NAME') AS CONTENEDOR
FROM DUAL;

SELECT USERNAME,
       ACCOUNT_STATUS,
       DEFAULT_TABLESPACE,
       TEMPORARY_TABLESPACE
FROM DBA_USERS
WHERE USERNAME = 'CADENA_NEGOCIOS';

SELECT TABLESPACE_NAME,
       STATUS,
       CONTENTS
FROM DBA_TABLESPACES
WHERE TABLESPACE_NAME IN ('TS_DATOS','TS_INDICES','TS_AUDITORIA')
ORDER BY TABLESPACE_NAME;
